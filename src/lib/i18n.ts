export const translations: Record<Locale, Record<string, string>> = raw;

export function detectLocale(browserLanguages: readonly string[]): Locale {
  for (const rawTag of browserLanguages) {
    const base = rawTag.slice(0, 2).toLowerCase();
    if ((SUPPORTED_LOCALES as readonly string[]).includes(base)) {
      return base as Locale;
    }
  }
  return DEFAULT_LOCALE;
}
